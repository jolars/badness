#!/usr/bin/env python3
"""Check or regenerate the pinned expl3 control-sequence deprecation table."""

import argparse
import datetime
import hashlib
from pathlib import Path
import urllib.request

REF = "3a56fdb57b0e8ff66ec5c72ab021001b028e22b8"
URL = f"https://raw.githubusercontent.com/latex3/latex3/{REF}/l3kernel/doc/l3obsolete.txt"
SHA256 = "dccdb6d030225f3191211d6b752a50c73ef1fae13edfe95d796d68c1127f643c"
OUTPUT = Path(__file__).resolve().parents[1] / "src/linter/expl3/deprecations.txt"


def generate(source: bytes) -> str:
    if hashlib.sha256(source).hexdigest() != SHA256:
        raise ValueError("l3obsolete.txt checksum mismatch")
    section = source.decode().split("Deprecated functions and variables\n", 1)[1]
    section = section.split("Removed functions and variables\n", 1)[0]
    entries = {}
    for line in section.splitlines():
        if line.startswith("\\"):
            name, date = line[1:].split()
            datetime.date.fromisoformat(date)
            if name in entries:
                raise ValueError(f"duplicate deprecation: {name}")
            entries[name] = date
    return f"# Generated by scripts/gen_expl3_deprecations.py from {URL}\n" + "".join(
        f"{name} {date}\n" for name, date in sorted(entries.items())
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--source", type=Path)
    args = parser.parse_args()
    if args.source:
        source = args.source.read_bytes()
    else:
        with urllib.request.urlopen(URL, timeout=30) as response:
            source = response.read()
    generated = generate(source).encode()
    if args.write:
        OUTPUT.write_bytes(generated)
    elif not OUTPUT.exists() or OUTPUT.read_bytes() != generated:
        parser.exit(1, "expl3 deprecations differ; run task expl3-deprecations:sync\n")


if __name__ == "__main__":
    main()
